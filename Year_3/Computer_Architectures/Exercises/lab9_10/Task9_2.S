;======= СЕГМЕНТ ДАННИ =============
	.data

X:  .word 100 
Y:  .word 200 

	; Форматиращ стринг
FrmStr:	.asciiz "Result=%d\n"	
	.align 2
	; Параметрична област ------
Par:	.word FrmStr
	; Резултат ------
Result:	.space		4

;======= КОДОВ СЕГМЕНТ ==============
	.text

    	; TODO:
	LW R1, X
	LW R2, Y
	ADD R2, R1, R2		; R2 = R1 + R2
	SW Result, R2

;------------------------------------
	lhi r14, Par >> 16		; старша полудума
	addui r14, r14, Par & 0xFFFF	; младша полудума
	trap 5				; printf()

	trap 0				; т.пр.