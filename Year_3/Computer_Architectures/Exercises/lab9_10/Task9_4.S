; ================================
; Задача 9.4
; Събиране на първите 100 числа.
; result: 5050
;---------------------------------
;   С-спецификация:
;---------------------------------
;   int sum = 0;
;   void main(void) {
;       for(i=0; i<=100; i++) {  
;           sum = sum + i;  
;       }
;       printf("Result=%d\n", sum);
;   }
;---------------------------------

;======= СЕГМЕНТ ДАННИ =============
    .data

    ; Форматиращ стринг
FrmStr: .asciiz "Result=%d\n"   
    .align 2
    ; Параметрична област ------
Par:    .word FrmStr
    ; Резултат ------
Result: .space      4

;======= КОДОВ СЕГМЕНТ ==============
    .text

    	; TODO:
	; R1 - index i
	; R2 - sum

	ADDI R2, R0, 0		; int sum = 0
	ADDI R1, R0, 0		; i = 0
Loop:
	SRLI R5, R1, 2		; R5 = R1 / 4 (деление на 4 = изместване надясно с 2 бита)
	SLE R4, R1, 100		; i <= 100
	BEQZ R4, Finish		; изход от цикъла
	ADD R2, R2, R1		; sum = sum + i
	ADDI R1, R1, 4		; i++
	J Loop
Finish:
	SW Result, R2

;------------------------------------
    lhi r14, Par >> 16      ; старша полудума
    addui r14, r14, Par & 0xFFFF    ; младша полудума
    trap 5              ; printf()

    trap 0              ; т.пр.