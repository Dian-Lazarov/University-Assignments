; Задача 9.6
; Намиране на максималния елемент в масив, 
; съдържащ 32-битови целочислени числа.
;---------------------------------
;   С-спецификация:
;---------------------------------
;   #define SIZE 10
;   int i;
;   int max;
;   int array[SIZE] = {-100, 210, 5, 0, 0, 0, 7, 8, -1, 4};
;   void main(void) {
;       max = array[0];
;       for(i = 1; i < SIZE; i++) {
;           if(max < array[i]) {
;               max = array[i];
;           }
;       }
;       printf("Max=%d\n", max);
;   }
;===================================
;  РЕГИСТРИ:
;  R2 - индекс
;  R3 - брояч на циклите
;  R4 - буфер
;  R5 - статус при сравнението
;  R10 - max
;  R14 - параметри на trap #5

;======= СЕГМЕНТ ДАННИ =============
	.data

	; Масив
	; int array[10];
Array:	.word -100, 210, 5, 0, 0, 0, 7, 8, -1, 4

	; Форматиращ стринг
FrmStr:	.asciiz "max=%d\n"
	.align 2
	; Параметрична област ------
Par:	.word FrmStr
	; Резултат ------
Max:	.space		4

;======= КОДОВ СЕГМЕНТ ==============
	.text

    ; TODO:
;------------------------------------
	lhi r14, Par >> 16		; старша полудума
	addui r14, r14, Par & 0xFFFF	; младша полудума
	trap 5				; printf()

	trap 0				; т.пр.