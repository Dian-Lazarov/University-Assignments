; Задача 9.1
; Събиране на две 32-битови числа чрез използване на непосредствена адресация
; 1000 + 2000 (DECIMAL)
; ================================

;======= СЕГМЕНТ ДАННИ =============
	.data

	; Форматиращ стринг
FrmStr:	.asciiz "Result=%d\n"	
	.align 2
	; Параметрична област ------
Par:	.word FrmStr
	; Резултат ------
Result:	.space 4

;======= КОДОВ СЕГМЕНТ ==============
	.text

    	; TODO:
	ADDI R1, R0, 1000	; R1 = 1000
	ADDI R2, R1, 2000	; R2 = R1 + 2000
	SW Result(R0), R2	; Result = R2

;------------------------------------
	lhi r14, Par >> 16		; старша полудума
	addui r14, r14, Par & 0xFFFF	; младша полудума
	trap 5				; printf()

	trap 0				; т.пр.