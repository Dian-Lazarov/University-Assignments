; ================================
; Задача 9.5
; Намиране на първия ненулев елемент в масив, 
; съдържащ 32-битови целочислени числа.
;---------------------------------
;   С-спецификация:
;---------------------------------
;   int size = 6;
;   int array[] = {100,200,300,400,500,600};
;   void main(void) {   
;       for(i=0; i<size; i++) {  
;           if (array[i] != 0) {
;               break;
;           }
;       }
;       if (i == size) {
;           printf("Not found\n");
;       } else {
;           printf("Result=%d\n", i);
;       }
;   }
;---------------------------------


;======= СЕГМЕНТ ДАННИ =============
    .data

    ; Масив
;Array:  .word 100,200,300,400,500,600 
;Array:  .word 0,0,300,400,500,600 
;Array:  .word 0,0,0,0,0,600 
Array:  .word 0,0,0,0,0,0 
Size:   .word 6 

    ; Параметрична област ------
Par:    .space  4
    ; Резултат ------
Result: .space  4

    ; Форматиращ стринг
FrmStr: .asciiz "Result=%d\n"   
    ; Стринг за ненамерен елемент
StrNotFound: .asciiz "Not found\n"   

;======= КОДОВ СЕГМЕНТ ==============
    .text

    ; РАЗПРЕДЕЛЕНИЕ НА РЕГИСТРИТЕ:
    ; R1 - отместване в байтове за достъп до паметта (0, 4, 8...)
    ; R3 - размер на масива (брой елементи, взети от Size)
    ; R6 - брояч на намерените ненулеви елементи (НОВО)
    
    ADDI R1, R0, 0      ; offset = 0
    LW R3, Size         ; R3 = 6
    ADDI R6, R0, 0      ; counter = 0 (нулираме брояча)

Loop:
    SRLI R5, R1, 2      ; R5 = R1 / 4 (получаваме реалния индекс 'i' - 0, 1, 2...)
    SLT R4, R5, R3      ; i < size ? (ПОПРАВКА: Сравняваме индекса R5, а не байтовете R1)
    BEQZ R4, Finish     ; Ако сме стигнали края на масива, излизаме от цикъла

    LW R2, Array(R1)    ; Зареждаме поредния елемент в R2
    SEQI R4, R2, 0      ; Проверяваме дали елементът е 0 (R4 = 1, ако R2 == 0)
    BNEZ R4, Next       ; Ако Е нула, прескачаме го и отиваме на следващия

    ; --- АКО ПРОГРАМАТА СТИГНЕ ДОТУК, ЕЛЕМЕНТЪТ Е НЕНУЛЕВ ---
    ADDI R6, R6, 1      ; Увеличаваме брояча на ненулевите елементи с 1
    SEQI R7, R6, 2      ; Проверяваме дали това е точно ВТОРИЯТ елемент (R6 == 2)
    BNEZ R7, Found      ; Ако да (R7 = 1), скачаме към етикета Found!

Next:
    ADDI R1, R1, 4      ; i++ (увеличаваме отместването с 4 байта за следващата дума)
    J Loop

Finish:
    J NotFound          ; Ако цикълът свърши без да сме намерили 2 елемента
    
;------------------------------------
Found:
    SW Result, R2       ; Записваме СТОЙНОСТТА на втория ненулев елемент в Result
    addi r14, r0, FrmStr
    sw  Par(r0), r14
    j Display
    
NotFound:
    addi r14, r0, StrNotFound
    sw  Par(r0), r14 
    
Display:    
    lhi r14, Par >> 16              ; старша полудума
    addui r14, r14, Par & 0xFFFF    ; младша полудума
    trap 5                          ; printf()
    trap 0                          ; край на програмата