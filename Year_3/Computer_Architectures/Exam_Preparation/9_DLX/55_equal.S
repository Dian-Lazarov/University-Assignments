; ================================
; Намиране на броя на елементите, равни на 55h
; съдържащ 32-битови целочислени числа.
;---------------------------------
;  РЕГИСТРИ:
;  R2 - байтово отместване (индекс)
;  R3 - брояч на итерациите (цикъла)
;  R4 - буфер за текущия елемент
;  R5 - статус при сравнението (1 ако е равно, 0 ако не е)
;  R6 - брояч на съвпаденията (резултат)
;  R14 - параметри на trap #5

;======= СЕГМЕНТ ДАННИ =============
	.data

	; Масив (променен с няколко стойности 85, за да тестваме брояча)
Array:	.word 85, 210, 85, 0, 0, 0, 7, 8, 85, 4

	; Форматиращ стринг за printf
FrmStr:	.asciiz "Count=%d\n"
	.align 2
	; Параметрична област ------
Par:	.word FrmStr
	; Резултат ------
Count:	.space		4

;======= КОДОВ СЕГМЕНТ ==============
	.text

	; --- ИНИЦИАЛИЗАЦИЯ ---
	ADDI R2, R0, 0		; Изместване = 0 (започваме от първия елемент, адрес 0)
	ADDI R3, R0, 10		; R3 = 10 (ще обходим всички 10 елемента)
	ADDI R6, R0, 0		; R6 = 0 (първоначално броят на съвпаденията е нула)

Loop:
	; --- ТЯЛО НА ЦИКЪЛА ---
	LW R4, Array(R2)	; Зареждаме поредния 32-битов елемент в буфера R4
	
	; Проверка дали елементът е равен на 55h (55х = 85 десетично)
	SEQI R5, R4, 85		; R5 = 1, ако R4 == 85, в противен случай R5 = 0
	BEQZ R5, Skip		; Ако R5 е 0 (не е равно), прескачаме инкрементирането

	; Ако е равно, увеличаваме брояча на съвпаденията
	ADDI R6, R6, 1		; R6 = R6 + 1

Skip:
	; --- УПРАВЛЕНИЕ НА ЦИКЪЛА ---
	ADDI R2, R2, 4		; Преминаваме към следващата дума (4 байта напред)
	SUBI R3, R3, 1		; Намаляваме оставащите итерации с 1
	BNEZ R3, Loop		; Ако остават още елементи (R3 != 0), въртим цикъла

	; --- ПОДГОТОВКА ЗА ИЗХОД ---
	SW Count, R6		; Записваме крайния брой в паметта на адрес Count

;------------------------------------
	; Извеждане на екрана чрез trap 5
	lhi r14, Par >> 16		; старша полудума
	addui r14, r14, Par & 0xFFFF	; младша полудума
	trap 5				; printf()

	trap 0				; край на програмата