; ================================
; Задача 9.6
; Намиране на максималния елемент в масив, 
; съдържащ 32-битови целочислени числа.
;---------------------------------
;   С-спецификация:
;---------------------------------
;   #define SIZE 10
;   int i;
;   int max;
;   int array[SIZE] = {-100, 210, 5, 0, 0, 0, 7, 8, -1, 4};
;   void main(void) {
;       max = array[0];
;       for(i = 1; i < SIZE; i++) {
;           if(max < array[i]) {
;               max = array[i];
;           }
;       }
;       printf("Max=%d\n", max);
;   }
;===================================
;  РЕГИСТРИ:
;  R2 - индекс
;  R3 - брояч на циклите
;  R4 - буфер
;  R5 - статус при сравнението
;  R10 - max
;  R14 - параметри на trap #5

;======= СЕГМЕНТ ДАННИ =============
	.data

	; Масив
	; int array[10];
Array:	.word -100, 210, 5, 0, 0, 0, 7, 8, -1, 4

	; Форматиращ стринг
FrmStr:	.asciiz "max=%d\n"
	.align 2
	; Параметрична област ------
Par:	.word FrmStr
	; Резултат ------
Max:	.space		4

;======= КОДОВ СЕГМЕНТ ==============
	.text

	; --- ИНИЦИАЛИЗАЦИЯ ---
	LW R10, Array		; max = array[0] (Зареждаме първия елемент в R10)
	ADDI R2, R0, 4		; i = 1 (Индексът R2 започва от 4 байта отместване)
	ADDI R3, R0, 9		; R3 = 9 (Остават 9 елемента за обхождане)

Loop:
	; --- ТЯЛО НА ЦИКЪЛА ---
	LW R4, Array(R2)	; Зареждаме array[i] в буфера R4
	
	; Проверка if(max < array[i])
	SLT R5, R10, R4		; R5 = 1, ако R10 (max) < R4 (array[i]), иначе R5 = 0
	BEQZ R5, Skip		; Ако R5 е 0 (max >= array[i]), прескачаме обновяването

	; Обновяване на максимума
	ADD R10, R0, R4		; max = array[i] (Копираме стойността от R4 в R10)

Skip:
	; --- УПРАВЛЕНИЕ НА ЦИКЪЛА ---
	ADDI R2, R2, 4		; Увеличаваме байтовото отместване (i++)
	SUBI R3, R3, 1		; Намаляваме брояча на итерациите с 1
	BNEZ R3, Loop		; Ако броячът не е станал 0, връщаме се в началото на цикъла

	; --- ПОДГОТОВКА ЗА ИЗХОД ---
	SW Max, R10		; Записваме намерения максимум в паметта на адрес Max

;------------------------------------
	; Извеждане на екрана чрез trap 5
	lhi r14, Par >> 16		; старша полудума
	addui r14, r14, Par & 0xFFFF	; младша полудума
	trap 5				; printf()

	trap 0				; край на програмата