JMP start
	; Тестов масив от 10 елемента (адреси от 02 до 0B)
	DB 00        ; Нула
	DB 00        ; Нула
	DB 00        ; Нула
	DB 1C        ; Първи ненулев елемент (CL ще стане 1)
	DB 24        ; Втори ненулев елемент (CL ще стане 2 -> ТУК СПИРАМЕ)
	DB FA
	DB 0B
	DB 00
	DB 55
	DB 55
cnt:
	DB 00        ; Клетка за резултата (адрес 0C)

start:
	MOV CL, 00   ; Нулираме брояча на открити ненулеви елементи
	MOV DL, 02   ; Насочваме указателя към първия елемент (адрес 02)

next:
	MOV AL, [DL] ; Зареждаме поредния елемент от масива в AL
	CMP AL, 00   ; Сравняваме го с 00 (нула)
	JZ skip      ; Ако Е нула (Z=1), прескачаме логиката за броене
	
	; Ако програмата стигне дотук, значи сме намерили число, различно от 00
	INC CL       ; Увеличаваме брояча на ненулевите елементи
	CMP CL, 02   ; Проверяваме дали това е ВТОРИЯТ открит елемент
	JZ found     ; Ако да (CL=2), скачаме към края! Числото вече е в AL.

skip:
	INC DL       ; Преместваме указателя на следващия адрес
	CMP DL, 0C   ; Проверяваме дали сме стигнали края на масива
	JNZ next     ; Ако не сме на края, връщаме се горе
	
	; Този код се изпълнява само ако в масива НЯМА два ненулеви елемента.
	; За да сме коректни, нулираме AL, за да покажем, че резултат не е намерен.
	MOV AL, 00
	JMP finish

found:
	; Тук попадаме веднага щом CL стане 2. 
	; Търсеният (втори) елемент се намира в AL.
	
finish:
	MOV [0C], AL ; Записваме намереното число (24) в клетката cnt
	HALT         ; Спиране на процесора
	END