jmp start
	; Тестов масив (адреси 02 - 06)
	db DA          ; -38 десетично
	db 1C          ; +28 десетично
	db 24          ; +36 десетично
	db FA          ; -6 десетично
	db 0B          ; +11 десетично
cnt:
	db 00          ; Клетка за резултата (намира се на адрес 07)

; Разпределение на работните регистри:
; AL - буфер за данни
; BL - текущ минимум
; DL - указател

start:	
	MOV DL, 02     ; Зареждаме началния адрес на масива
	MOV BL, [DL]   ; Приемаме първия елемент за минимален (BL = DA)
loop:
	INC DL         ; Преминаваме към следващия адрес
	CMP DL, 07     ; Проверка дали сме обходили целия масив
	JZ finish      ; Ако да, излизаме от цикъла
	MOV AL, [DL]   ; Вземаме поредния елемент в буфера AL
	CMP BL, AL     ; Сравняваме текущия минимум (BL) с новия елемент (AL)
	JS skip        ; ПРОМЯНА: Ако BL < AL (S=1), съхраняваме BL и пропускаме
	MOV BL, [DL]     ; Ако DL е по-малък (S=0), обновяваме минимума в BL
skip:
	JMP loop       ; Повторение на цикъла
finish:
	MOV [07], BL   ; Записваме крайния минимум в клетка 07 (cnt)
	HALT           ; Спиране на процесора
	end