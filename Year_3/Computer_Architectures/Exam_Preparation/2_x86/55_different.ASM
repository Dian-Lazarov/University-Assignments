cnt:
	DB 00        ; адрес 0C - клетка за резултата
	
; Разпределение на работните регистри
; AL - буферен регистър
; CL - резултат
; DL - индексен регистър за достъп до масива

start:
	MOV CL, 0    ; Нулираме брояча за резултата
	MOV DL, 02   ; Насочваме указателя към първия елемент (адрес 02)
next:
	MOV AL, [DL] ; Вземаме поредния елемент в AL
	CMP AL, 55   ; Сравняваме с 55h
	JZ skip      ; Ако разликата е нула (числата са равни, Z=1), пропускаме
	INC CL       ; Ако разликата не е нула, значи са различни -> увеличаваме брояча
skip:
	INC DL       ; Преместваме указателя на следващия адрес в паметта
	CMP DL, 0C   ; Проверяваме дали сме достигнали края на масива (адрес 0C)
	JNZ next     ; Ако не сме, връщаме се за следващия елемент
	
	MOV [0C], CL ; Записваме крайния брой в клетката cnt
	HALT         ; Физическо спиране на процесора
	END