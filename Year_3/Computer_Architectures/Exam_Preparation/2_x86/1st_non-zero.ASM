JMP start
	; Тестов масив от 10 елемента (адреси от 02 до 0B)
	DB 00        ; Нула (пропускаме)
	DB 00        ; Нула (пропускаме)
	DB 00        ; Нула (пропускаме)
	DB 1C        ; Първи ненулев елемент! (Това търсим)
	DB 24
	DB FA
	DB 0B
	DB 00
	DB 55
	DB 55
cnt:
	DB 00        ; Клетка за резултата (адрес 0C)

start:
	MOV DL, 02   ; Насочваме указателя към първия елемент (адрес 02)

next:
	MOV AL, [DL] ; Зареждаме поредния елемент от масива в AL
	CMP AL, 00   ; Сравняваме го с 00 (нула)
	JNZ found    ; Ако НЕ е нула (Z=0), скачаме директно към етикета 'found'
	
	; Ако стигнем дотук, значи числото Е било нула. Продължаваме търсенето:
	INC DL       ; Преместваме указателя на следващия адрес
	CMP DL, 0C   ; Проверяваме дали сме стигнали края на масива
	JNZ next     ; Ако не сме на края, връщаме се горе за следващия елемент
	
	; Този ред се изпълнява само ако ЦЕЛИЯТ масив е пълен с нули.
	; В този случай AL вече си съдържа 00, така че направо отиваме към запис.
	JMP finish

found:
	; Тук попадаме веднага щом JNZ "хване" ненулево число.
	; Търсеното число вече се намира готово в регистър AL.
	
finish:
	MOV [0C], AL ; Записваме намереното число (или 00, ако няма такова) в клетка cnt
	HALT         ; Спиране на процесора
	END