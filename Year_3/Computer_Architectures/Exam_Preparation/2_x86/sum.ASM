JMP start
	DB 01
	DB 02
	DB 03
	DB 04
	DB 05
	DB 06
	DB 07
	DB 08
	DB 09
	DB 0A

; Разпределение на работните регистри:
; AL – резултат
; BL – буфер за данни
; DL – указател

start:
	MOV DL, 02	; Насочваме указателя към първия елемент (адрес 02)
	MOV AL, 0	; Нулираме първоначалната сума

sum_loop:
	MOV BL, [DL]  	; Вземаме поредния елемент от паметта
	ADD AL, BL 	; Събираме го с натрупания резултат (AL = AL + BL)

	CMP DL, 0B	; Проверяваме дали сме обработили последния елемент (адрес 0B)
	JZ finish	; Ако сме на последния елемент, излизаме от цикъла

	INC DL 		; Ако не сме, преместваме указателя към следващия адрес
	JMP sum_loop	; Въртим цикъла

finish:
	MOV [C0], AL
	HALT
	END