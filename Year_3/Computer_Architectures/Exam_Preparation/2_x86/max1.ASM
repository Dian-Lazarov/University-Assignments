jmp start
	; Тестов масив (адреси 02 - 06)
	db DA          ; -38 десетично
	db 1C          ; +28 десетично
	db 24          ; +36 десетично
	db FA          ; -6 десетично
	db 0B          ; +11 десетично

; Разпределение на работните регистри:
; AL - буфер за данни
; BL - текущ максимум
; DL - указател

start:	
	MOV DL, 02   ; Зареждаме началния адрес на масива
	MOV BL, [DL] ; Приемаме първия елемент за максимален
loop:
	INC DL       ; Преминаваме към следващия адрес
	CMP DL, 07   ; Извън масива ли сме? (кодът започва от адрес 07)
	JZ finish    ; Ако да, отиваме към извеждане
	MOV AL, [DL] ; Вземаме поредния елемент в AL
	CMP BL, AL   ; Сравняваме текущия максимум с новия елемент
	JNS skip     ; Ако BL >= AL, пропускаме
	MOV BL, [DL]   ; Обновяваме максимума в BL
skip:
	JMP loop     ; Повторение на цикъла
finish:
	MOV [C0], BL ; Извеждаме стойността директно на първа позиция на екрана (адрес C0)
	HALT         ; Спиране на процесора
	end