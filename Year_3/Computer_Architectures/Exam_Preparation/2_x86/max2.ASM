jmp start
	; Тестов масив (адреси 02 - 06)
	db DA
	db 1C
	db 24
	db FA
	db 0B
cnt:
	db 00        ; Клетка за резултата <cnt> (намира се на адрес 07)

; Разпределение на работните регистри:
; AL - буфер за данни
; BL - текущ максимум
; DL - указател

start:	
	MOV DL, 02   ; Зареждаме началния адрес на масива
	MOV BL, [DL] ; Приемаме първия елемент за максимален
loop:
	INC DL       ; Преминаваме към следващия адрес
	CMP DL, 07   ; Проверка дали сме обходили целия масив (адрес 07 е клетката cnt)
	JZ finish    ; Ако сме стигнали крайната граница, излизаме от цикъла
	MOV AL, [DL] ; Вземаме поредния елемент в буфера AL
	CMP BL, AL   ; Сравняваме текущия максимум (BL) с новия елемент (AL)
	JNS skip     ; Ако BL >= AL (няма знак за отрицателно число), пропускаме
	MOV BL, [DL]   ; Ако DL е по-голям, обновяваме максимума в BL
skip:
	JMP loop     ; Повторение на цикъла
finish:
	MOV [07], BL ; Записваме натрупания максимум в клетката <cnt> (адрес 07)
	HALT         ; Спиране на процесора
	end