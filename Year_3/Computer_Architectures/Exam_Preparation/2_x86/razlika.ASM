JMP start
	; Тестов масив от 10 елемента (адреси от 02 до 0B)
	DB 01
	DB 02
	DB 03
	DB 04
	DB 05
	DB 06
	DB 07
	DB 08
	DB 09
	DB 0A

; Разпределение на работните регистри:
; AL – резултат
; BL – буфер за данни
; DL – указател

start:
	MOV DL, 02    ; Насочваме указателя към първия елемент (адрес 02)
	MOV AL, [DL]  ; Зареждаме първия елемент в AL (Това е стартовата ни база: 01)
	INC DL        ; Преместваме указателя на втория елемент (адрес 03), за да започнем ваденето от него

diff_loop:
	MOV BL, [DL]  ; Вземаме поредния елемент от паметта
	SUB AL, BL    ; Изваждаме го от натрупания резултат (AL = AL - BL)
	
	CMP DL, 0B    ; Проверяваме дали сме обработили последния елемент (адрес 0B)
	JZ finish     ; Ако сме на последния елемент, излизаме от цикъла
	
	INC DL        ; Ако не сме, преместваме указателя към следващия адрес
	JMP diff_loop ; Въртим цикъла

finish:
	MOV [0C], AL  ; Записваме крайния резултат в свободна клетка (0C)
	HALT          ; Спираме процесора
	END